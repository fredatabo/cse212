    // Run 10 times.
    // Expected Result: Tim, Sue, Tim, Sue, Tim, Sue, Tim, Tim, Tim, Tim
    // Defect(s) Found: A person with negative turns (-3) was never re-enqueued and was at risk
    // of having Turns decremented, corrupting the infinite sentinel. After treating Turns <= 0
